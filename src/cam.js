    const app = this.app, c = this.cam, r = this.res;
    const bodies = this.solidBodies();
    if (!bodies.some((b) => b.id === c.body)) c.body = bodies[0]?.id || null;
    const opRes = (id) => r?.ops.find((o) => o.id === id);
